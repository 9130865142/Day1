// if Statement
let user = 15;
if (user >= 18) {
    console.log("You are eligible to vote.")
} 



// if-else Statement
if (user >= 20) {
    console.log("You are   eligible to vote.")
}else{
    console.log("You are not eligible to vote.")
}



// if-else if-else Statement
if (user >= 18) {
    console.log("You are  eligible to vote.")
}else if (user == 18) {
    console.log("You are also  eligible to vote.")
}else {
    console.log("You are  not eligible to vote.")
}




// switch statement
switch (user) {
    case 18:
        console.log("You are  eligible to vote.");
        break;
    case 20:
        console.log("You are  eligible to vote.");
        break;
    default:
        console.log("You are  not eligible to vote.");
        break;
}





// LOOPING CONDITIONS
// for loop
for (i=1; i<=4; i++){
    console.log(i);
}

// while loop
let b = 3;
while(b <= 5){
    console.log(b);
    b++;
}



// do-while loop
let c = 1;
do {    console.log(c);
    c++;
}while (c <= 4);





